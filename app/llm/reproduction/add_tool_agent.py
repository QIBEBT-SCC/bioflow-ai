def db_format(bio_dbs: list[BioDb]):
    formatted = [
        (
            f'   <db>\n'
            f'      <db_id>{db.id}</db_id>\n'
            f'      <db_name>{db.name}</db_name>\n'
            f'      <desc>{db.description}</desc>\n'
            f'   </db>'
        )
        for db in bio_dbs
    ]

    return '\n\n'.join(formatted)


class DBSelectResult(BaseModel):
    """从现有数据库中的选择结果"""

    id: int = Field(description='适配的数据库id')
    error: str = Field(description='如果没有合适的数据库，将你的反馈信息写在这个字段里')


class AddToolState(MessagesState):
    image: ImageConfig
    tool_name: str
    help_doc: str
    help_doc_id: int
    origin_query: str

    extra_db: str
    container_id: str
    output_files: str
    last_log: str

    tool_uid: str
    error: AIMessage


class AddToolOutput(BaseModel):
    tool_uid: str
    error: AIMessage


class AddToolAgent:
    def __init__(self):
        self.llm = gemini_25_flash()
        self.structure_llm = gpt_41_mini()

        self.run_command_tool = RunCommandInContainer()

    @staticmethod
    @tool
    def search_db(tool_name: Annotated[str, InjectedToolArg]):
        """查看现有生物信息数据库列表"""
        with Session(engine) as session:
            local_db = db_crud.get_by_name_fuzzy(session, tool_name, 50, 0)

        return local_db

    @staticmethod
    @tool
    def view_log():
        """查看日志输出的最后20行"""
        return

    def manage_mount_node(self, state: AddToolState):
        """首先判断工具是否需要数据库"""
        state['messages'] = [HumanMessage(content=state['help_doc'])]

        prompt = ChatPromptTemplate(messages=[SystemMessage(content=CHECK_DB_SYSTEM), ('human', '{doc}')])
        llm = self.structure_llm.bind_tools([self.search_db])
        chain = prompt | llm

        response = chain.invoke({'doc': state['help_doc']})

        return {'messages': [response]}

    def search_db_node(self, state: AddToolState) -> Command[Literal['create_container_node', 'close_container_node']]:
        """根据判断结果，查询数据库或者直接继续"""
        last_message = state['messages'][-1]
        if last_message.tool_calls:
            exist_dbs = self.search_db.invoke({'tool_name': state['tool_name']})
            if len(exist_dbs) == 0:
                return Command(goto='close_container_node')

            prompt = ChatPromptTemplate(
                messages=[
                    SystemMessage(content=CHECK_DB_SYSTEM),
                    MessagesPlaceholder(variable_name='history'),
                    ToolMessage(
                        content=CHECK_DB_USER.format(db_info=db_format(exist_dbs)),
                        tool_call_id=last_message.tool_calls[0]['id'],
                    ),
                ]
            )
            llm = self.structure_llm.with_structured_output(DBSelectResult)
            # formatter = itemgetter('dbs') | RunnableLambda(db_format)
            # chain = RunnablePassthrough.assign(db_info=formatter) | prompt | llm
            chain = prompt | llm

            result: DBSelectResult = chain.invoke({'history': state['messages']})

            if result.id:
                with Session(engine) as session:
                    tool_db: BioDb = db_crud.get(session, result.id)

                state['messages'].clear()
                return Command(goto='create_container_node', update={'extra_db': tool_db.path})

            return Command(goto='close_container_node', update={'error': AIMessage(content='db not found')})
        else:
            state['messages'].clear()
            return Command(goto='create_container_node')

    @staticmethod
    def create_container_node(state: AddToolState):
        # TODO 改成配置设定
        mounts = [
            Mount(
                target='/data/raw', source='/mnt/sda/gene/yeyu/Program/bioflow-ai-testdata', type='bind', read_only=True
            )
        ]
        if 'extra_db' in state and state['extra_db']:
            db_path = str(Path(state['extra_db']).parent) if Path(state['extra_db']).is_file() else state['extra_db']
            mounts.append(Mount(target='/data/db', source=db_path, type='bind', read_only=True))

        container_id = create_container(state['image'], mounts)

        init_template = (
            '{query}\n\n<help_doc>{doc}</help_doc>\n\nTool db has been mounted to `/data/db`'
            if 'extra_db' in state
            else '{query}\n\n<help_doc>{doc}</help_doc>'
        )
        return {
            'container_id': container_id,
            'messages': [
                HumanMessage(content=init_template.format(query=state['origin_query'], doc=state['help_doc']))
            ],
        }

    def generate_command_node(self, state: AddToolState):
        prompt = ChatPromptTemplate(messages=[('system', TEST_RUN_SYS), MessagesPlaceholder(variable_name='history')])
        llm = self.llm.bind_tools([self.run_command_tool, self.view_log])
        chain = prompt | llm

        # TODO 从配置读入
        with open('/mnt/sda/gene/yeyu/Program/bioflow-ai-testdata/DESCRIPTION.md', 'r') as f:
            data_desc = f.read()
        response = chain.invoke({'testdata_description': data_desc, 'history': state['messages']})

        return {'messages': response}

    @staticmethod
    def should_continue(state: AddToolState) -> Literal['run_command_node', 'view_log_node', 'generate_config_node']:
        latest_msg = state['messages'][-1]
        if latest_msg.tool_calls:
            if latest_msg.tool_calls[0]['name'] == 'view_log':
                return 'view_log_node'
            return 'run_command_node'
        else:
            return 'generate_config_node'

    def run_command_node(self, state: AddToolState):
        last_message = state['messages'][-1]
        tool_call: ToolCall = last_message.tool_calls[0]
        tool_call_id = tool_call['id']

        last_log = ''
        try:
            logger.info(tool_call['args'])
            tool_msg = self.run_command_tool.invoke({**tool_call['args'], 'container_id': state['container_id']})
            if len(tool_msg) == 0:
                tool_msg = 'Done'
            elif len(tool_msg) > 1000:
                last_log = tool_msg
                tool_msg = 'Done, log has saved, use `view_log` to read it.'
        except ToolException as e:
            tool_msg = str(e)

        logger.debug(tool_msg)
        return {'messages': [ToolMessage(content=tool_msg, tool_call_id=tool_call_id)], 'last_log': last_log}

    @staticmethod
    def view_log_node(state: AddToolState):
        last_message = state['messages'][-1]
        tool_call: ToolCall = last_message.tool_calls[0]
        tool_call_id = tool_call['id']

        # 1. 将日志字符串按行分割成列表
        all_lines = state['last_log'].splitlines()

        # 2. 获取末尾 20 行内容（这部分是“pop”出来的）
        # 使用 max(0, len(all_lines) - 20) 确保即使行数不足20行也不会出错
        start_index = max(0, len(all_lines) - 20)
        popped_lines = all_lines[start_index:]

        # 3. 构造新的日志字符串（去除末尾 20 行后的内容）
        remaining_lines = all_lines[:start_index]
        new_log = '\n'.join(remaining_lines)
        end_log = '\n'.join(popped_lines)

        return {'messages': [ToolMessage(content=end_log, tool_call_id=tool_call_id)], 'last_log': new_log}

    def generate_config_node(self, state: AddToolState):
        prompt = ChatPromptTemplate.from_messages(
            [SystemMessage(content=TOOL_GEN_SYSTEM), ('human', TOOL_GEN_USER_WITH_REPORT)]
        )
        chain = prompt | self.structure_llm.with_structured_output(AIGenTool)

        output: AIGenTool = chain.invoke(
            {
                'help_doc': state['help_doc'],
                'user_require': state['origin_query'],
                'report': state['messages'][-1].content,
            }
        )

        with Session(engine) as session:
            tag = tag_crud.ai_gen_tag(session)
            tool_uid = uuid7(as_type='str')
            new_tool = ToolData(
                uid=str(tool_uid),
                name=output.name,
                description=output.description,
                tags=[tag],
                tool_type=ToolType.DOCKER,
                command_template=output.command_template,
                homepage='',
                dynamic_params=output.dynamic_params,
                static_params=output.static_params,
                output_files=output.output_files,
                help_doc_id=state['help_doc_id'],
                mkdir_output=output.mkdir_output,
                use_temp_dir=output.use_temp_dir,
                docker_config=DockerConfig(image=state['image'], docker_settings={}),
            )
            tool_crud.insert(session, new_tool)

        return {'tool_uid': tool_uid}

    @staticmethod
    def close_container_node(state: AddToolState):
        if 'container_id' in state and state['container_id']:
            remove_container(state['container_id'])
        return {}

    def build(self, visualize: bool = False) -> CompiledStateGraph:
        graph = StateGraph(AddToolState, output=AddToolOutput)

        graph.add_node('manage_mount_node', self.manage_mount_node)
        graph.add_node('search_db_node', self.search_db_node)
        graph.add_node('create_container_node', self.create_container_node)
        graph.add_node('generate_command_node', self.generate_command_node)
        graph.add_node('run_command_node', self.run_command_node)
        graph.add_node('view_log_node', self.view_log_node)
        graph.add_node('generate_config_node', self.generate_config_node)
        graph.add_node('close_container_node', self.close_container_node)

        graph.set_entry_point('manage_mount_node')
        graph.add_edge('manage_mount_node', 'search_db_node')
        graph.add_edge('create_container_node', 'generate_command_node')
        graph.add_conditional_edges(
            'generate_command_node', self.should_continue, ['run_command_node', 'view_log_node', 'generate_config_node']
        )
        graph.add_edge('run_command_node', 'generate_command_node')
        graph.add_edge('view_log_node', 'generate_command_node')
        graph.add_edge('generate_config_node', 'close_container_node')
        graph.set_finish_point('close_container_node')

        compiled_graph = graph.compile()

        if visualize:
            compiled_graph.get_graph(xray=True).draw_mermaid_png(
                output_file_path='add_tool_agent.png',
                draw_method=MermaidDrawMethod.API,
                curve_style=CurveStyle.BASIS,
                frontmatter_config={'config': {'theme': 'redux', 'look': 'neo'}},
            )

        return compiled_graph
