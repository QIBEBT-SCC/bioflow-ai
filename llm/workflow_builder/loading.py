"""Load a persisted workflow template into workflow-builder editing state."""

from dataclasses import dataclass

from sqlalchemy.orm import Session

from app.crud.tools import tool as tool_crud
from app.schemas.react_flow import WorkflowDefinition
from app.schemas.tools import Handle, ToolNodePublic
from app.schemas.workflow_config import ExecutionScope
from app.utils.input_format import build_command_template
from llm.states import BuildEdge, BuildNode, WorkflowDraft
from llm.utils.node_schema import PROCESSORS, RESOURCES
from llm.workflow_builder.node_ids import canonicalize_build_graph, has_canonical_node_ids
from llm.workflow_builder.subgraphs import effective_nodes, remap_interface


class WorkflowLoadError(ValueError):
    """A persisted workflow cannot be represented by the builder managers."""


@dataclass(frozen=True)
class LoadedWorkflowDraft:
    """Canonical editing draft plus its persisted-to-editing node ID mapping."""

    draft: WorkflowDraft
    node_id_mapping: dict[str, str]


def _handle_name(handle: str, node_id: str, direction: str) -> str:
    prefix = f'{node_id}-{direction}-'
    return handle.removeprefix(prefix)


def _tool_node(node_id: str, data: dict, session: Session) -> BuildNode:
    tool_uid = data.get('tool_uid')
    if not tool_uid:
        message = f'Tool node {node_id} has no tool_uid.'
        raise WorkflowLoadError(message)
    db_tool = tool_crud.get(session, tool_uid)
    if db_tool is None:
        message = f'Tool node {node_id} references missing tool {tool_uid}.'
        raise WorkflowLoadError(message)
    tool = ToolNodePublic.model_validate(db_tool)
    modifiable_params = data.get('modifiable_params')
    command = build_command_template(
        db_tool.command_template,
        db_tool.dynamic_params,
        db_tool.immutable_static_params,
        modifiable_params,
        db_tool.file_mounts,
    )
    return BuildNode(
        id=node_id,
        name=tool.name,
        type='tool',
        input_handles=tool.input_handles,
        output_handles=tool.output_handles,
        data=dict(data),
        command=command,
    )


def _registered_node(node_id: str, node_type: str, data: dict) -> BuildNode | None:
    resource_type = node_type.removeprefix('resource_') if node_type.startswith('resource_') else node_type
    if resource_type in RESOURCES and (node_type.startswith('resource_') or node_type == 'value_string'):
        schema = RESOURCES[resource_type]
        return BuildNode(
            id=node_id,
            name=schema['name'],
            type=node_type,
            input_handles=schema['input_handles'],
            output_handles=schema['output_handles'],
            data=dict(data),
        )
    if node_type in PROCESSORS:
        schema = PROCESSORS[node_type]
        return BuildNode(
            id=node_id,
            name=schema['name'],
            type=node_type,
            input_handles=schema['input_handles'],
            output_handles=schema['output_handles'],
            data=dict(data),
        )
    return None


def _fixed_node(node_id: str, node_type: str, data: dict) -> BuildNode | None:
    if node_type == 'subgraph':
        child = WorkflowDefinition.model_validate(data.get('workflow'))
        if child.interface is None:
            message = f'Subgraph {node_id} has no interface.'
            raise WorkflowLoadError(message)
        return BuildNode(
            id=node_id,
            name=str(data.get('name') or 'Subgraph'),
            type='subgraph',
            input_handles=[Handle(name=port.id, description=port.description) for port in child.interface.inputs],
            output_handles=[Handle(name=port.id, description=port.description) for port in child.interface.outputs],
            data=dict(data),
        )
    if node_type in {'code_bash', 'code_python', 'code_R'}:
        language = {'code_bash': 'Bash', 'code_python': 'Python', 'code_R': 'R'}[node_type]
        return BuildNode(
            id=node_id,
            name=f'{language} Code',
            type=node_type,
            input_handles=[Handle(name='input_files', description=f'The files required by this {language} code')],
            output_handles=[Handle(name='output_folder', description='The files generated by this code')],
            data=dict(data),
        )
    if node_type == 'note':
        return BuildNode(id=node_id, name='note', type=node_type, input_handles=[], output_handles=[], data=dict(data))
    if node_type == 'downstream_summary':
        return BuildNode(
            id=node_id,
            name='downstream_summary',
            type=node_type,
            input_handles=[Handle(name='input_files', description='The files required for downstream analyse')],
            output_handles=[],
            data=dict(data),
        )
    return None


def load_workflow_draft(
    workflow: WorkflowDefinition,
    *,
    name: str,
    description: str,
    execution_scope: ExecutionScope,
    session: Session,
    preserve_ids: bool = False,
) -> LoadedWorkflowDraft:
    """Restore a persisted definition as the single active Fix draft."""
    nodes: list[BuildNode] = []
    for node in workflow.nodes:
        if node.type == 'tool':
            restored = _tool_node(node.id, node.data, session)
        else:
            restored = _registered_node(node.id, node.type, node.data) or _fixed_node(node.id, node.type, node.data)
        if restored is None:
            message = f'Unsupported workflow node type {node.type!r} at node {node.id}.'
            raise WorkflowLoadError(message)
        nodes.append(restored)

    edges = [
        BuildEdge(
            source_node=edge.source,
            source_handle=_handle_name(edge.sourceHandle, edge.source, 'out'),
            target_node=edge.target,
            target_handle=_handle_name(edge.targetHandle, edge.target, 'in'),
        )
        for edge in workflow.edges
    ]
    if preserve_ids or has_canonical_node_ids(nodes):
        id_mapping = {node.id: node.id for node in nodes}
    else:
        try:
            nodes, edges, id_mapping = canonicalize_build_graph(nodes, edges)
        except ValueError as error:
            raise WorkflowLoadError(str(error)) from error

    try:
        nodes = effective_nodes(nodes, edges)
    except ValueError as error:
        raise WorkflowLoadError(str(error)) from error

    scope = 'project_level' if execution_scope == ExecutionScope.PROJECT_LEVEL else 'sample_level'
    return LoadedWorkflowDraft(
        draft=WorkflowDraft(
            draft_id='fix_target',
            name=name,
            description=description,
            execution_scope=scope,
            nodes=nodes,
            edges=edges,
            interface=remap_interface(workflow.interface, id_mapping),
            next_node_index=len(nodes) + 1,
        ),
        node_id_mapping=id_mapping,
    )
